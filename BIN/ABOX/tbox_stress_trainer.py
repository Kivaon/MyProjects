    def load_stress_dict(self) -> Dict[str, str]:
        """Загружает словарь ударений из файла"""
        if os.path.exists(self.stress_file):
            try:
                with open(self.stress_file, 'r', encoding='utf-8') as f:
                    return json.load(f)
            except Exception as e:
                print(f"Ошибка загрузки словаря: {e}")
                return {}
        return {}
    
    def save_stress_dict(self):
        """Сохраняет словарь ударений в файл"""
        try:
            with open(self.stress_file, 'w', encoding='utf-8') as f:
                json.dump(self.stress_dict, f, ensure_ascii=False, indent=2)
            print(f"✅ Словарь сохранен: {self.stress_file}")
        except Exception as e:
            print(f"Ошибка сохранения словаря: {e}")
    
    def add_stress(self, word: str, stressed_word: str):
        """Добавляет слово с ударением в словарь"""
        self.stress_dict[word.lower()] = stressed_word
        self.save_stress_dict()
        print(f"✅ Добавлено: {word} → {stressed_word}")
    
    def find_stress_errors(self, text: str) -> List[str]:
        """Находит слова без ударений в тексте"""
        import re
        
        # Извлекаем слова из текста
        words = re.findall(r'\b[а-яё]+\b', text.lower())
        
        # Находим слова без ударений
        errors = []
        for word in words:
            if word not in self.stress_dict and len(word) > 2:
                errors.append(word)
        
        return list(set(errors))  # Убираем дубликаты
    
    def generate_training_text(self) -> str:
        """Генерирует текст для тренировки с правильными ударениями"""
        training_sentences = []
        
        # Берем слова из словаря и создаем предложения
        words_list = list(self.stress_dict.keys())
        
        # Создаем предложения по темам
        themes = {
            'работа': ['менеджер', 'звонит', 'говорит', 'документ', 'каталог'],
            'еда': ['торты', 'свекла', 'лук', 'пекарня'],
            'техника': ['телефон', 'компас', 'сантиметр'],
            'профессии': ['бухгалтер', 'столяр', 'маляр', 'ветеринария'],
            'качество': ['красивый', 'хороший', 'важный', 'интересный'],
        }
        
        for theme, theme_words in themes.items():
            available_words = [w for w in theme_words if w in self.stress_dict]
            if available_words:
                sentence = f"На {theme} работают {', '.join(available_words)}."
                training_sentences.append(sentence)
        
        # Добавляем отдельные слова
        for i in range(0, len(words_list), 5):
            chunk = words_list[i:i+5]
            stressed_chunk = [self.stress_dict[w] for w in chunk if w in self.stress_dict]
            if stressed_chunk:
                training_sentences.append('. '.join(stressed_chunk) + '.')
        
        return '\n\n'.join(training_sentences)
    
    def update_preprocessor(self):
        """Обновляет словарь в предобработчике"""
        preprocessor_file = "/Users/kivaonmac/Documents/AI_Lab/BIN/tbox_tts_preprocessor.py"
        
        try:
            with open(preprocessor_file, 'r', encoding='utf-8') as f:
                content = f.read()
            
            # Находим словарь в предобработчике
            import re
            
            # Создаем новый словарь
            new_dict_lines = ["        self.stress_dict = {"]
            for word, stressed in sorted(self.stress_dict.items()):
                new_dict_lines.append(f"            '{word}': '{stressed}',")
            new_dict_lines.append("        }")
            
            # Заменяем старый словарь на новый
            pattern = r'self\.stress_dict = \{[^}]+\}'
            new_dict_text = '\n'.join(new_dict_lines)
            
            content = re.sub(pattern, new_dict_text, content, flags=re.DOTALL)
            
            # Сохраняем обновленный предобработчик
            with open(preprocessor_file, 'w', encoding='utf-8') as f:
                f.write(content)
            
            print(f"✅ Предобработчик обновлен: {preprocessor_file}")
            
        except Exception as e:
            print(f"Ошибка обновления предобработчика: {e}")
    
    def show_statistics(self):
        """Показывает статистику словаря"""
        total_words = len(self.stress_dict)
        themes = {
            'Глаголы': 0, 'Существительные': 0, 'Прилагательные': 0
        }
        
        # Простая классификация по окончаниям
        for word in self.stress_dict.keys():
            if word.endswith(('ит', 'ят', 'ишь', 'ает', 'яют', 'ешь')):
                themes['Глаголы'] += 1
            elif word.endswith(('ый', 'ая', 'ое', 'ие', 'ия')):
                themes['Прилагательные'] += 1
            else:
                themes['Существительные'] += 1
        
        print(f"📊 СТАТИСТИКА СЛОВАРЯ УДАРЕНИЙ:")
        print(f"   Всего слов: {total_words}")
        for theme, count in themes.items():
            print(f"   {theme}: {count}")
        
        # Показываем последние добавленные слова
        print(f"\n📝 ПОСЛЕДНИЕ ДОБАВЛЕННЫЕ СЛОВА:")
        recent_words = list(self.stress_dict.items())[-10:]
        for word, stressed in recent_words:
            print(f"   {word} → {stressed}")

