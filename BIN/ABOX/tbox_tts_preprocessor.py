    def preprocess_text(self, text: str) -> str:
        """Основная функция предобработки текста"""
        
        # 1. Исправляем стандартные ошибки
        text = self._correct_standard_errors(text)
        
        # 2. Добавляем ударения
        text = self._add_stress_marks(text)
        
        # 3. Дополнительная очистка
        text = self._final_cleanup(text)
        
        return text
    
    def _correct_standard_errors(self, text: str) -> str:
        """Исправляет стандартные ошибки в тексте"""
        corrected_text = text
        
        # Заменяем слова из словаря исправлений
        for wrong, correct in self.corrections.items():
            corrected_text = corrected_text.replace(wrong, correct)
        
        return corrected_text
    
    def _add_stress_marks(self, text: str) -> str:
        """Добавляет ударения в слова"""
        words = text.split()
        stressed_words = []
        
        for word in words:
            # Очищаем слово от пунктуации
            clean_word = re.sub(r'[^\w]', '', word.lower())
            
            # Проверяем в словаре ударений
            if clean_word in self.stress_dict:
                stressed_word = self.stress_dict[clean_word]
                
                # Восстанавливаем пунктуацию
                prefix = re.match(r'^[^\w]*', word).group()
                suffix = re.search(r'[^\w]*$', word).group()
                
                # Сохраняем ударение
                stressed_words.append(prefix + stressed_word + suffix)
            else:
                stressed_words.append(word)
        
        return ' '.join(stressed_words)
    
    def _final_cleanup(self, text: str) -> str:
        """Финальная очистка текста"""
        # Убираем лишние пробелы
        text = re.sub(r'\s+', ' ', text).strip()
        
        # Убираем специальные символы, которые могут мешать TTS
        text = re.sub(r'[^\w\s\.\,\!\?\;\:\-\(\)]', '', text)
        
        return text
    
    def add_word_to_dictionary(self, word: str, stressed_word: str):
        """Добавляет слово в словарь ударений"""
        self.stress_dict[word.lower()] = stressed_word
        print(f"✅ Добавлено: {word} → {stressed_word}")
    
    def add_correction(self, wrong: str, correct: str):
        """Добавляет исправление в словарь ошибок"""
        self.corrections[wrong] = correct
        print(f"✅ Добавлено исправление: {wrong} → {correct}")
    
    def show_dictionary_stats(self):
        """Показывает статистику словарей"""
        print(f"📊 СТАТИСТИКА ПРЕДОБРАБОТЧИКА:")
        print(f"   Слов с ударениями: {len(self.stress_dict)}")
        print(f"   Исправлений ошибок: {len(self.corrections)}")
        
        print(f"\n📝 ПРИМЕРЫ УДАРЕНИЙ:")
        for word, stressed in list(self.stress_dict.items())[:10]:
            print(f"   {word} → {stressed}")

